"""Shareable HTML report: verdict, stitch-count chart, and findings.

Self-contained (inline CSS, no external assets) so it can be emailed,
hosted, or printed. Written counts only â€” never a measurement.
"""

from __future__ import annotations

import html
from pathlib import Path

from .calculators import shape_from_counts, stitch_count_chart


def _counts(pattern) -> list[int]:
    items = pattern.rounds or pattern.rows
    counts: list[int] = []
    prev = 0
    for i, item in enumerate(items):
        try:
            value = (
                item.computed_stitch_count
                if i == 0
                else item.compute_stitch_count_with_context(prev)
            )
        except Exception:
            value = prev
        counts.append(int(value or 0))
        prev = int(value or 0)
    return counts


def _bar_chart(counts: list[int]) -> str:
    data = stitch_count_chart(counts)
    if not data:
        return "<p>No rounds parsed.</p>"
    peak = max(d["stitches"] for d in data) or 1
    rows = "".join(
        f'<div class="bar-row"><span class="bar-label">R{d["round"]}</span>'
        f'<span class="bar-track"><span class="bar-fill" style="width:{d["pct_of_max"]}%"></span></span>'
        f'<span class="bar-value">{d["stitches"]}</span></div>'
        for d in data
    )
    return f'<div class="chart">{rows}</div><p class="muted">Peak: {peak} stitches. Written counts, not a measurement.</p>'


def build_report(pattern, report) -> str:
    counts = _counts(pattern)
    title = html.escape(getattr(pattern.metadata, "title", "") or "Crochet pattern")
    status = html.escape(str(report.overall_status))
    errors = "".join(
        f"<li><b>[{html.escape(str(e.location))}]</b> {html.escape(e.message)}</li>"
        for e in report.errors
    )
    warnings = "".join(
        f"<li><b>[{html.escape(str(w.location))}]</b> {html.escape(w.message)}</li>"
        for w in report.warnings
    )
